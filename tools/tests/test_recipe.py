from pathlib import Path

import pytest
import yaml

from qp import feed, recipe
from qp.feed import FeedEntry

GOLDEN = Path(__file__).parent / "golden"


def entry(slug="demo", version="1.0", plugin_id="7") -> FeedEntry:
    return FeedEntry(
        slug=slug,
        version=version,
        plugin_id=plugin_id,
        name=slug,
        download_url=feed.DOWNLOAD_URL.format(slug=slug, version=version),
        experimental=False,
        deprecated=False,
    )


@pytest.mark.parametrize(
    ("qgis_min", "qgis_max", "expected"),
    [
        ("3.32.0", "4.99.99", "3.40"),
        ("3.40.5", "4.99.99", "3.40"),  # the line overlaps the range
        ("3.41.0", "4.99.99", "3.44"),
        ("4.0.0", "4.99.99", None),  # only the newest line: the unpinned test covers it
        ("3.0.0", "3.38.99", None),  # no test line in range
    ],
)
def test_oldest_test_line(qgis_min, qgis_max, expected):
    assert recipe.oldest_test_line(["4.2", "3.40", "3.44"], qgis_min, qgis_max) == expected


def test_generate(demo_zip):
    r = recipe.generate(entry(), demo_zip, ["3.40", "4.2"])
    assert r.name == "qgis-plugin-demo"
    assert r.dirname == "qgis-plugin-demo-1.0"
    data = r.data
    assert data["context"] == {
        "plugin": "demo",
        "version": "1.0",
        "qgis_min": "3.32.0",
        "qgis_max": "4.99.99",
    }
    assert data["requirements"]["run"] == ["qgis >=${{ qgis_min }},<=${{ qgis_max }}"]
    assert [t["requirements"]["run"] for t in data["tests"][1:]] == [["qgis"], ["qgis 3.40.*"]]
    assert data["about"]["license"] == "GPL-2.0-or-later"
    assert data["extra"]["qgis_plugin_id"] == "7"


def test_generate_rejects_version_mismatch(demo_zip):
    with pytest.raises(ValueError, match="metadata.txt version 1.0 != feed 1.1"):
        recipe.generate(entry(version="1.1"), demo_zip, ["4.2"])


def test_write(demo_zip, tmp_path):
    out = recipe.write(recipe.generate(entry(), demo_zip, ["4.2"]), tmp_path)
    assert sorted(p.name for p in out.iterdir()) == ["build.sh", "recipe.yaml", "test_plugin.py"]
    text = (out / "recipe.yaml").read_text()
    assert text.startswith("# Generated by `qp generate`")
    # Versions stay strings when read back, e.g. "1.0" mustn't become a float.
    assert yaml.safe_load(text)["context"]["version"] == "1.0"


@pytest.mark.network
def test_golden_quick_map_services(tmp_path):
    """The generated QMS 1.5.2 recipe equals the hand-written reference (docs/plan.md M1)."""
    data = feed.download("quick_map_services", "1.5.2", tmp_path)
    generated = recipe.generate(
        entry("quick_map_services", "1.5.2", "663"), data, ["3.40", "3.44", "4.2"]
    )
    golden = yaml.safe_load((GOLDEN / "quick_map_services-1.5.2" / "recipe.yaml").read_text())
    assert generated.data == golden
